-- [PostgreSQL] 2. Contributors, the cleaned landslides table, and raw -> clean.
-- One transaction: if anything fails, nothing is left half-loaded.

BEGIN;

-- Who can submit reports (C1) and edit their own (C2)
CREATE TABLE contributors (
    id                  integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username            text NOT NULL UNIQUE,
    institution         text,
    created_at          timestamptz NOT NULL DEFAULT now()
);

-- Cleaned, typed table: the operational source of truth
CREATE TABLE landslides (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- BY DEFAULT: original ids can be inserted
    geom                geometry(Point, 4326),
    source_dataset      text NOT NULL,                     -- where the row came from ('Contributor portal' for C1)
    source_id           text,
    source_version      text,
    country             text,
    accuracy_m          integer,
    start_date          date NOT NULL,                     -- when the event happened
    end_date            date NOT NULL,
    type                text,
    physical_factors    text,                              -- the trigger
    reliability         smallint,
    record_type         text,
    fatalities          integer,
    injuries            integer,
    notes               text,
    link                text,
    submitted_by        integer REFERENCES contributors(id),  -- NULL for all original UGLC rows
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),   -- drives the sync; C2 must set it itself
    CHECK (end_date >= start_date)
);

-- Raw -> clean. Unknown-value sentinels ('ND', -99999, 'Source: ND', ...) become real NULLs,
-- so ClickHouse later just copies clean data. 17 columns, 17 values, same order.
INSERT INTO landslides (id, geom, source_dataset, source_id, source_version, country, accuracy_m,
                        start_date, end_date, type, physical_factors, reliability, record_type,
                        fatalities, injuries, notes, link)
SELECT  id::numeric::bigint,                                                            -- 1  id
        CASE WHEN wkt_geom LIKE '%Infinity%'                                            -- 2  geom: 9 USGS rows are
             THEN NULL                                                                  --    POINT (-Infinity -Infinity)
             ELSE ST_GeomFromText(wkt_geom, 4326)
        END,
        old_dataset,                                                                    -- 3  source_dataset
        old_id,                                                                         -- 4  source_id
        version,                                                                        -- 5  source_version
        country,                                                                        -- 6  country
        NULLIF(accuracy, '-99999')::numeric::integer,                                   -- 7  accuracy_m
        LEAST(to_date(start_date, 'YYYY/MM/DD'), to_date(end_date, 'YYYY/MM/DD')),      -- 8  start_date } 109 rows have
        GREATEST(to_date(start_date, 'YYYY/MM/DD'), to_date(end_date, 'YYYY/MM/DD')),   -- 9  end_date   } end < start: swap
        NULLIF(type, 'ND'),                                                             -- 10 type
        NULLIF(physical_factors, 'ND'),                                                 -- 11 physical_factors
        reliability::numeric::smallint,                                                 -- 12 reliability
        record_type,                                                                    -- 13 record_type
        CASE WHEN fatality ~ '^[0-9]+(\.[0-9]+)?$'                                      -- 14 fatalities: 3 Oregon (DOGAMI)
             THEN fatality::numeric::integer                                            --    rows hold text here ('Sunken
        END,                                                                            --    pavement', ...) -> NULL, like -99999
        NULLIF(injuries, '-99999')::numeric::integer,                                   -- 15 injuries
        NULLIF(notes, 'ND'),                                                            -- 16 notes
        CASE WHEN link IN ('Source: ND', 'Source: ''ND''', 'Source: Unknown')           -- 17 link
             THEN NULL
             ELSE link
        END
FROM raw_points;

-- Move the id counter past the original ids, otherwise the first C1 report hits "duplicate key"
SELECT setval(pg_get_serial_sequence('landslides', 'id'), (SELECT MAX(id) FROM landslides));

COMMIT;
